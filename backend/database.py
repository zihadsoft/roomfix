# POSTGRESQL TABLES
# ==========================================

def initialize_postgres(conn):

    conn.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY
                PRIMARY KEY,
            name TEXT NOT NULL,
            email TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            role TEXT NOT NULL
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS rooms (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY
                PRIMARY KEY,
            room_number TEXT UNIQUE NOT NULL,
            status TEXT NOT NULL DEFAULT 'available'
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS maintenance_requests (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY
                PRIMARY KEY,
            title TEXT NOT NULL,
            description TEXT NOT NULL,
            location TEXT NOT NULL,
            priority TEXT NOT NULL
                CHECK (
                    priority IN ('low', 'medium', 'high')
                ),
            status TEXT NOT NULL DEFAULT 'pending'
                CHECK (
                    status IN (
                        'pending',
                        'assigned',
                        'in_progress',
                        'completed',
                        'rejected'
                    )
                ),
            created_by INTEGER NOT NULL
                REFERENCES users(id),
            assigned_staff INTEGER
                REFERENCES users(id),
            rejection_reason TEXT,
            is_deleted INTEGER NOT NULL DEFAULT 0,
            deleted_at TEXT,
            deleted_by INTEGER REFERENCES users(id),
            created_at TEXT NOT NULL
                DEFAULT CURRENT_TIMESTAMP,
            updated_at TEXT NOT NULL
                DEFAULT CURRENT_TIMESTAMP
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS assignment_history (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY
                PRIMARY KEY,
            request_id INTEGER NOT NULL
                REFERENCES maintenance_requests(id)
                ON DELETE CASCADE,
            from_staff INTEGER REFERENCES users(id),
            to_staff INTEGER NOT NULL REFERENCES users(id),
            assigned_by INTEGER NOT NULL REFERENCES users(id),
            action TEXT NOT NULL DEFAULT 'assigned',
            note TEXT,
            created_at TEXT NOT NULL
                DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # Add columns for older PostgreSQL schemas.
    conn.execute("""
        ALTER TABLE maintenance_requests
        ADD COLUMN IF NOT EXISTS rejection_reason TEXT
    """)

    conn.execute("""
        ALTER TABLE maintenance_requests
        ADD COLUMN IF NOT EXISTS
        is_deleted INTEGER NOT NULL DEFAULT 0
    """)

    conn.execute("""
        ALTER TABLE maintenance_requests
        ADD COLUMN IF NOT EXISTS deleted_at TEXT
    """)

    conn.execute("""
        ALTER TABLE maintenance_requests
        ADD COLUMN IF NOT EXISTS
        deleted_by INTEGER REFERENCES users(id)
    """)


# ==========================================
# SQLITE TABLES
# ==========================================

def initialize_sqlite(conn):

    conn.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            email TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            role TEXT NOT NULL
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS rooms (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            room_number TEXT UNIQUE NOT NULL,
            status TEXT NOT NULL DEFAULT 'available'
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS maintenance_requests (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            description TEXT NOT NULL,
            location TEXT NOT NULL,
            priority TEXT NOT NULL
                CHECK (
                    priority IN ('low','medium','high')
                ),
            status TEXT NOT NULL DEFAULT 'pending'
                CHECK (
                    status IN (
                        'pending','assigned','in_progress',
                        'completed','rejected'
                    )
                ),
            created_by INTEGER NOT NULL
                REFERENCES users(id),
            assigned_staff INTEGER REFERENCES users(id),
            rejection_reason TEXT,
            is_deleted INTEGER NOT NULL DEFAULT 0,
            deleted_at TEXT,
            deleted_by INTEGER REFERENCES users(id),
            created_at TEXT NOT NULL
                DEFAULT CURRENT_TIMESTAMP,
            updated_at TEXT NOT NULL
                DEFAULT CURRENT_TIMESTAMP
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS assignment_history (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            request_id INTEGER NOT NULL
                REFERENCES maintenance_requests(id)
                ON DELETE CASCADE,
            from_staff INTEGER REFERENCES users(id),
            to_staff INTEGER NOT NULL REFERENCES users(id),
            assigned_by INTEGER NOT NULL REFERENCES users(id),
            action TEXT NOT NULL DEFAULT 'assigned',
            note TEXT,
            created_at TEXT NOT NULL
                DEFAULT CURRENT_TIMESTAMP
        )
    """)

    columns = {
        row[1]
        for row in conn.execute(
            "PRAGMA table_info(maintenance_requests)"
        ).fetchall()
    }

    migrations = {
        "rejection_reason": "TEXT",
        "is_deleted": "INTEGER NOT NULL DEFAULT 0",
        "deleted_at": "TEXT",
        "deleted_by": "INTEGER REFERENCES users(id)"
    }

    for name, definition in migrations.items():
        if name not in columns:
            conn.execute(
                f"ALTER TABLE maintenance_requests "
                f"ADD COLUMN {name} {definition}"
            )


