DATABASE_URL = os.getenv("DATABASE_URL")
USE_POSTGRES = bool(DATABASE_URL)

DB_PATH = Path(
    os.getenv(
        "ROOMFIX_DB_PATH",
        str(Path(__file__).resolve().parent / "roomfix.db")
    )
)

